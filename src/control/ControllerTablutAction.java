package control;

import boardifier.control.Controller;
import boardifier.control.ControllerAction;
import boardifier.model.GameException;
import boardifier.model.Model;
import boardifier.view.View;
import javafx.event.ActionEvent;
import javafx.event.EventHandler;
import view.TablutRootPane;
import model.TablutOptionModel;
import view.TablutView;

/**
 * A basic action controller that only manages menu actions
 * Action events are mostly generated when there are user interactions with widgets like
 * buttons, checkboxes, menus, ...
 */
public class ControllerTablutAction extends ControllerAction implements EventHandler<ActionEvent> {

    // to avoid lots of casts, create an attribute that matches the instance type.
    private final TablutView tablutView;


    public ControllerTablutAction(Model model, View view, Controller control) {
        super(model, view, control);
        // take the view parameter ot define a local view attribute with the real instance type, i.e. BasicView.
        tablutView = (TablutView) view;

        // set handlers dedicated to menu items
        setMenuHandlers();

        // If needed, set the general handler for widgets that may be included within the scene.
        // In this case, the current gamestage view must be retrieved and casted to the right type
        // in order to have an access to the widgets, and finally use setOnAction(this).
        // For example, assuming the current gamestage view is an instance of MyGameStageView, which
        // creates a Button myButton :
        // ((MyGameStageView)view.getCurrentGameStageView()).getMyButton().setOnAction(this).

    }

    private void setMenuHandlers() {

        EventHandler<ActionEvent> handlerNewGame = event -> {
            try {
                model.getPlayers().clear();
                model.reset();
                setPlayers();

                control.startGame();


                System.out.println(TablutOptionModel.getGamemode());

                if (TablutOptionModel.getGamemode() >= 2) {
                    model.setNextPlayer();
                    control.endOfTurn();
                }
            } catch (GameException err) {
                System.err.println(err.getMessage());
                System.exit(1);
            }
        };

        EventHandler<ActionEvent> handlerIntro = event -> {
            control.stopGame();
            tablutView.resetView();
        };
        EventHandler<ActionEvent> handlerQuit = event -> System.exit(0);

        EventHandler<ActionEvent> handlerSetting = event -> {
            tablutView.resetView();
            tablutView.showOptionMenu();
        };


        tablutView.getMenuStart().setOnAction(handlerNewGame);
        tablutView.getMenuIntro().setOnAction(handlerIntro);
        tablutView.getMenuQuit().setOnAction(handlerQuit);
        tablutView.getMenuOption().setOnAction(handlerSetting);

        TablutRootPane rootPane = (TablutRootPane) tablutView.getRootPane();
        rootPane.getBtnNewGame().setOnAction(handlerNewGame);
        rootPane.getBtnSettings().setOnAction(handlerSetting);
        rootPane.getBtnQuit().setOnAction(handlerQuit);


    }

    /**
     * The general handler for action events.
     * this handler should be used if the code to process a particular action event is too long
     * to fit in an arrow function (like with menu items above). In this case, this handler must be
     * associated to a widget w, by calling w.setOnAction(this) (see constructor).
     *
     * @param event An action event generated by a widget of the scene.
     */
    public void handle(ActionEvent event) {
        if (!model.isCaptureActionEvent()) return;
    }

    public void setPlayers() {
        switch (TablutOptionModel.getGamemode()) {
            case 0 -> {
                model.addHumanPlayer("swedish player");
                model.addHumanPlayer("muscovite player");
            }
            case 1 -> {
                model.addHumanPlayer("swedish player");
                model.addComputerPlayer("muscovite computer");
            }
            case 2 -> {
                model.addComputerPlayer("swedish computer");
                model.addHumanPlayer("muscovite player");
            }
            case 3 -> {
                model.addComputerPlayer("swedish computer");
                model.addComputerPlayer("muscovite computer");
            }
        }
    }
}

